#!/bin/bash
# Install or update ddeonmadeit plug-ins on macOS from Terminal:
#   curl -fsSL https://ddeonmadeit.github.io/plugins-/install.sh | bash                    every plug-in (skips ones already up to date)
#   curl -fsSL https://ddeonmadeit.github.io/plugins-/install.sh | bash -s Sunburst        just the ones you name
#   curl -fsSL https://ddeonmadeit.github.io/plugins-/install.sh | bash -s -- --reinstall  install again even if up to date
# It runs the same .pkg installers as the download buttons. Files fetched with curl don't get the
# browser's download-quarantine flag, so macOS doesn't show "Apple could not verify ..." for them.
#
# The copy on the site is generated by tools/site/build_site.py from the newest releases.
# Written for macOS's built-in bash 3.2: no associative arrays, no ${x,,}, no set -u with empty arrays.

main ()
{
    set -eo pipefail

    if [[ "$(uname -s)" != Darwin ]]; then
        echo "This installer is for macOS."
        exit 1
    fi

    # name|version|pkg url|sha256 of the newest release of each plug-in
    local releases=(
        "Afterglow|1.14.0|https://github.com/ddeonmadeit/plugins-/releases/download/Afterglow-v1.14.0/Afterglow-1.14.0-macOS.pkg|1cd865bfc6019a9ad68dc280a8e4b9585fc5d0f0c2ccd8874a7c63c8eed1c6f8"
        "Aircheck|1.6.0|https://github.com/ddeonmadeit/plugins-/releases/download/Aircheck-v1.6.0/Aircheck-1.6.0-macOS.pkg|99cfca1bf8ea00d21bfa17ba62b77ca15bf1ca45d3871700bf0ea7864f9c9536"
        "Contour|1.3.0|https://github.com/ddeonmadeit/plugins-/releases/download/Contour-v1.3.0/Contour-1.3.0-macOS.pkg|d35739b009c908d8aa22616224c6611de17df0f53425cf6e98e498fb0d99f98e"
        "Hush|1.3.0|https://github.com/ddeonmadeit/plugins-/releases/download/Hush-v1.3.0/Hush-1.3.0-macOS.pkg|f3dce1d2c5cd963a8b70b49241d32864babd9f2694754bbc4d479c60f0f00959"
        "Kitroom|1.16.0|https://github.com/ddeonmadeit/plugins-/releases/download/Kitroom-v1.16.0/Kitroom-1.16.0-macOS.pkg|90f1444a7fcde9e5d4c817784fac8f7d6688f6002736cba2287dc2c9bc64ee46"
        "Mirage|1.3.0|https://github.com/ddeonmadeit/plugins-/releases/download/Mirage-v1.3.0/Mirage-1.3.0-macOS.pkg|4d5dd7ed2181bde2c8f2ab3b0db6403cf0b0d9b15a3fe86f81f3dcf18a542f1a"
        "Orbit|1.2.0|https://github.com/ddeonmadeit/plugins-/releases/download/Orbit-v1.2.0/Orbit-1.2.0-macOS.pkg|3c6a338096294fbd929c64d6c32a2651eeffd0e2803a6d8d1d909e43392d3b06"
        "SubGrit|1.15.0|https://github.com/ddeonmadeit/plugins-/releases/download/SubGrit-v1.15.0/SubGrit-1.15.0-macOS.pkg|1265148ea9fc87956ce450511280e75f16a36064f9cc879b1acf47381ca5ce2c"
        "Sunburst|1.10.0|https://github.com/ddeonmadeit/plugins-/releases/download/Sunburst-v1.10.0/Sunburst-1.10.0-macOS.pkg|12ae27f2dbebe6c892b8d2e1f77ca5b54f0d9707acd2b6e67713ab099a0d6745"
    )

    local reinstall=0 want=() arg
    for arg in "$@"; do
        case "$arg" in
            --reinstall) reinstall=1 ;;
            --) ;;
            -*) echo "Unknown option $arg"; exit 1 ;;
            *) want+=("$arg") ;;
        esac
    done

    shopt -s nocasematch
    local picked=() line name w found
    for w in "${want[@]}"; do
        found=0
        for line in "${releases[@]}"; do
            [[ "${line%%|*}" == "$w" ]] && found=1
        done
        if (( ! found )); then
            echo "No plug-in called \"$w\". Available: $(names "${releases[@]}")"
            exit 1
        fi
    done
    for line in "${releases[@]}"; do
        name="${line%%|*}"
        if (( ${#want[@]} == 0 )); then
            picked+=("$line")
        else
            for w in "${want[@]}"; do
                [[ "$name" == "$w" ]] && picked+=("$line")
            done
        fi
    done
    shopt -u nocasematch

    # Work out what needs installing before asking for a password.
    local todo=() version url sha installed
    for line in "${picked[@]}"; do
        IFS='|' read -r name version url sha <<< "$line"
        installed="$(installed_version "$name")"
        if [[ "$installed" == "$version" && $reinstall == 0 ]]; then
            echo "$name $version is already installed."
        else
            todo+=("$line")
        fi
    done
    if (( ${#todo[@]} == 0 )); then
        echo "Everything is up to date."
        exit 0
    fi

    echo
    echo "Installing into /Library/Audio/Plug-Ins: $(names "${todo[@]}")"
    echo "macOS asks for your Mac password (the one you log in with). Nothing shows while you type; press Return."
    sudo -v

    # Global, not local: the EXIT trap runs after main has returned.
    DD_TMP="$(mktemp -d "${TMPDIR:-/tmp}/ddeonmadeit.XXXXXX")"
    trap 'rm -rf "$DD_TMP"' EXIT

    for line in "${todo[@]}"; do
        IFS='|' read -r name version url sha <<< "$line"
        echo
        echo "== $name $version"
        local pkg="$DD_TMP/$name-$version-macOS.pkg"
        curl -fL --progress-bar --retry 3 -o "$pkg" "$url"
        if [[ -n "$sha" ]]; then
            local got
            got="$(shasum -a 256 "$pkg" | cut -d ' ' -f 1)"
            if [[ "$got" != "$sha" ]]; then
                echo "The download of $name didn't arrive intact (checksum mismatch). Run the command again."
                exit 1
            fi
        fi
        sudo installer -pkg "$pkg" -target / < /dev/null
        rm -f "$pkg"

        # An older copy from the zip's Install.command (user plug-in folders) would show up twice in
        # the host, or win over the new one. Move it to the Trash rather than deleting it.
        local old
        for old in "$HOME/Library/Audio/Plug-Ins/VST3/$name.vst3" "$HOME/Library/Audio/Plug-Ins/Components/$name.component"; do
            if [[ -e "$old" ]]; then
                mkdir -p "$HOME/.Trash"
                mv "$old" "$HOME/.Trash/$(basename "$old" | sed "s/\./ (old $(date +%H%M%S))./")"
                echo "  moved an older copy to the Trash: $old"
            fi
        done
    done

    # Make macOS re-scan Audio Units.
    killall -9 AudioComponentRegistrar 2> /dev/null || true

    echo
    echo "Done. If your DAW is open, restart it."
    echo "  FL Studio: new plug-ins appear after Options > Manage plugins > Find more plugins."
    echo "  Ableton Live: Settings > Plug-Ins, turn on Use Audio Units and Use VST3 Plug-In System Folders, click Rescan."
}

installed_version ()
{
    local plist="/Library/Audio/Plug-Ins/VST3/$1.vst3/Contents/Info.plist"
    if [[ -f "$plist" ]]; then
        /usr/libexec/PlistBuddy -c "Print :CFBundleShortVersionString" "$plist" 2> /dev/null || true
    fi
}

names ()
{
    local out="" line
    for line in "$@"; do
        out="$out${out:+, }${line%%|*}"
    done
    echo "$out"
}

# Everything above is only definitions, so a download cut short can't run half a script.
main "$@"
